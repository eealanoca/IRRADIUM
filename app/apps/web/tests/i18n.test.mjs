import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,dirname} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const web=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output=resolve(mkdtempSync(resolve(tmpdir(),'irradium-i18n-')),'translation.mjs');
await build({entryPoints:[resolve(web,'lib/i18n/translate.ts')],bundle:true,format:'esm',platform:'node',outfile:output});
const {translate,localize}=await import(pathToFileURL(output));
assert.equal(translate('Y','en'),'Y');
for (const symbol of ['La','Ne','Y','H2','Co60']) assert.equal(translate(symbol,'en'),symbol);
assert.equal(translate('Centro [x, y, z]','en'),'Center [x, y, z]');
assert.equal(translate('Posiciones','en'),'Positions');
assert.equal(translate('Tasas del estudio','en'),'Study dose rates');
assert.equal(translate('Dosis y tiempos','en'),'Dose and time');
assert.equal(translate('25.920 vóxeles · 2 cm','en'),'25.920 voxels · 2 cm');
assert.equal(translate('123.456 S17 water_001','en'),'123.456 S17 water_001');
const dom=new JSDOM('<body><h1>Tasas del estudio</h1><button title="Pausar">Pausar</button><input value="Carga del usuario"><pre>fuentes</pre><span data-i18n-skip>Posiciones</span><a href="http://localhost/api/learning/guide">Guía PDF</a></body>');
for(const key of ['document','NodeFilter','HTMLAnchorElement','HTMLOptionElement'])globalThis[key]=dom.window[key];
const records=new WeakMap(),attributes=new WeakMap();
const heading=document.querySelector('h1').firstChild;
localize(document.body,'en',records,attributes);
assert.equal(document.querySelector('h1').textContent,'Study dose rates');
assert.equal(document.querySelector('button').title,'Pause');
assert.equal(document.querySelector('input').value,'Carga del usuario');
assert.equal(document.querySelector('pre').textContent,'fuentes');
assert.equal(document.querySelector('span').textContent,'Posiciones');
assert.equal(document.querySelector('h1').firstChild,heading,'React text-node identity must be preserved');
assert.ok(document.querySelector('a').href.endsWith('language=en'));
localize(document.body,'es',records,attributes);
assert.equal(document.querySelector('h1').textContent,'Tasas del estudio');
assert.equal(document.querySelector('button').title,'Pausar');
heading.nodeValue='Dosis y tiempos';
localize(document.body,'en',records,attributes);
assert.equal(heading.nodeValue,'Dose and time','React updates are translated from their new source');
console.log('PASS English/Spanish labels, restoration, dynamic text, attributes, guide links, node identity and user data');
